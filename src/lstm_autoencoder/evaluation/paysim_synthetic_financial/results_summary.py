"""Summarize experiment reports into markdown tables for the Results section.

Reads only the JSON reports already written under ``artifacts/report`` (no
training, no data loading, so it is cheap to run) and writes one markdown file
with:

1. Training grid: standalone LSTM-AE test AUC per window x architecture.
2. Baselines: LR ablation (+ GBM control) and unsupervised baselines.
3. Hybrid classifier: per window x architecture, AUC/AP/recall@FPR per variant
   and the key paired deltas.

Architecture labels of training reports come from the ``run_config`` block
written by the training pipeline (verified). Older reports have no such block,
so their label is only inferred from the typed command and is listed
separately as unverified.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from lstm_autoencoder.config import DatasetConfig
from lstm_autoencoder.reporting.console_report import ConsoleReporter

ARCHITECTURE_ORDER: tuple[str, ...] = ("attn", "bottleneck", "plain", "attn_pool")
DEFAULT_LEGACY_SINCE = "20261106_103302"
DEFAULT_OUTPUT = Path("artifacts") / "summary" / "results_summary.md"


@dataclass(frozen=True)
class ResultsSummaryConfig:
    """Settings for the results summary."""

    legacy_since: str = DEFAULT_LEGACY_SINCE
    output_path: Path | None = None


class ResultsSummarizer:
    """Turn the JSON reports of one dataset into markdown result tables."""

    def __init__(
        self,
        dataset_config: DatasetConfig,
        summary_config: ResultsSummaryConfig | None = None,
        reporter: ConsoleReporter | None = None,
    ) -> None:
        """Bind the summarizer to a dataset's report folder."""
        self._dataset_config = dataset_config
        self._config = summary_config or ResultsSummaryConfig()
        self._reporter = reporter or ConsoleReporter()
        self._report_root = dataset_config.artifacts_dir / "report" / dataset_config.dataset_name

    def run(self) -> Path:
        """Write the markdown summary and return its path."""
        text = "\n\n".join(
            [
                "# Results summary (generated by the `summarize-results` command)",
                self._training_section(),
                self._baseline_section(),
                self._hybrid_section(),
            ]
        )
        output_path = self._config.output_path or self._dataset_config.project_root / DEFAULT_OUTPUT
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(text + "\n", encoding="utf-8")
        self._reporter.display_text(f"Result is saved on: {output_path}")
        return output_path

    def _reports(self, pipeline: str) -> list[tuple[str, dict]]:
        """Return (timestamp, report) for every JSON report of `pipeline`, oldest first."""
        found = [
            (path.parent.name, json.loads(path.read_text(encoding="utf-8")))
            for path in (self._report_root / pipeline).glob("*/*/*.json")
        ]
        return sorted(found, key=lambda item: item[0])

    def _training_section(self) -> str:
        """Standalone LSTM-AE training grid."""
        verified: dict[tuple[int, str], dict] = {}
        legacy: list[tuple[str, int, str, dict]] = []
        for stamp, report in self._reports("model_training"):
            multi = report.get("multi_seed_training")
            if not multi:
                continue
            run_config = report.get("run_config")
            if run_config:
                verified[(run_config["window_length"], run_config["architecture"])] = multi  # latest wins
            elif stamp >= self._config.legacy_since:
                window = multi["runs"][0]["window_length"]
                legacy.append((stamp, window, self._architecture_from_command(report.get("command", "")), multi))

        out = ["## 1. LSTM-AE standalone (test AUC, mean ± std over seeds)\n"]
        if verified:
            windows = sorted({window for window, _ in verified})
            rows = []
            for architecture in ARCHITECTURE_ORDER:
                row = [architecture]
                for window in windows:
                    multi = verified.get((window, architecture))
                    row.append(
                        self._format(multi["aggregate"]["test_auc_mean"], multi["aggregate"]["test_auc_std"])
                        if multi
                        else "-"
                    )
                rows.append(row)
            out.append("Verified reports (architecture recorded in `run_config`):\n")
            out.append(self._table(["architecture"] + [f"W={window}" for window in windows], rows))
        else:
            out.append("_No verified (run_config) training reports yet._")

        if legacy:
            out.append(
                "\nLegacy reports WITHOUT `run_config` (label inferred from the typed command, UNVERIFIED; "
                "identical numbers under different labels indicate a mislabeled or duplicated run):\n"
            )
            rows = [
                [
                    stamp,
                    f"W={window}",
                    architecture,
                    self._format(multi["aggregate"]["test_auc_mean"], multi["aggregate"]["test_auc_std"]),
                    ",".join(str(run["best_epoch"]) for run in multi["runs"]),
                ]
                for stamp, window, architecture, multi in legacy
            ]
            out.append(self._table(["report", "window", "label (unverified)", "test AUC", "best epochs"], rows))
        return "\n".join(out)

    def _baseline_section(self) -> str:
        """LR/GBM ablation plus unsupervised baselines (latest report of each)."""
        out = ["## 2. Baselines (test split)\n"]
        baseline = self._reports("baseline")
        if baseline:
            stamp, report = baseline[-1]
            rows = [
                [name, self._format(v["overall"]["test_auc"]), self._format(v["overall"]["test_ap"])]
                for name, v in report["ablation"].items()
            ]
            out.append(f"Supervised ablation (report {stamp}):\n")
            out.append(self._table(["model", "test AUC", "test AP"], rows))

            # Add side-by-side per-bucket table for baseline variants
            by_bucket_section = self._baseline_by_bucket_table(report["ablation"])
            if by_bucket_section:
                out.append("\n" + by_bucket_section)

        unsupervised = self._reports("unsupervised_baselines")
        if unsupervised:
            stamp, report = unsupervised[-1]
            aggregate = report["unsupervised_baselines"]["aggregate"]
            rows = [
                [
                    name,
                    self._format(v["auc_mean"], v["auc_std"]),
                    self._format(v["ap_mean"], v["ap_std"]),
                    self._format(v["recall_at_fpr_0.01_mean"], digits=3),
                ]
                for name, v in aggregate["models"].items()
            ]
            out.append(f"\nUnsupervised baselines (report {stamp}, {aggregate['n_seeds']} seeds):\n")
            out.append(self._table(["model", "test AUC", "test AP", "recall@FPR 1%"], rows))
        return "\n".join(out)

    def _hybrid_section(self) -> str:
        """Hybrid classifier results: latest report per (window, architecture)."""
        latest: dict[tuple[int, str], tuple[str, dict]] = {}
        for stamp, report in self._reports("hybrid_classifier"):
            hybrid = report.get("hybrid_classifier")
            if hybrid:
                latest[(hybrid["window_length"], hybrid["architecture"])] = (stamp, hybrid)

        out = ["## 3. Hybrid classifier (LR features + LSTM-AE reconstruction error)\n"]
        if not latest:
            return out[0] + "_No hybrid reports found._"
        ordered = sorted(latest.items(), key=lambda item: (item[0][0], self._architecture_rank(item[0][1])))
        for (window, architecture), (stamp, hybrid) in ordered:
            aggregate = hybrid["aggregate"]
            out.append(f"### W={window}, {architecture} (report {stamp}, seeds={hybrid['seeds']})\n")
            rows = [
                [
                    name,
                    self._format(v["auc_mean"], v["auc_std"]),
                    self._format(v["ap_mean"], v["ap_std"]),
                    self._format(v["recall_at_fpr_0.01_mean"], digits=3),
                ]
                for name, v in aggregate["variants"].items()
            ]
            out.append(self._table(["variant", "test AUC", "test AP", "recall@FPR 1%"], rows))
            rows = [
                [
                    name,
                    self._format(v["d_auc_mean"], v["d_auc_std"]),
                    self._format(v["d_ap_mean"], v["d_ap_std"]),
                    self._ci_count(v),
                ]
                for name, v in aggregate["deltas"].items()
            ]
            out.append(
                "\nPaired deltas (candidate - reference); last column = number of seeds whose bootstrap CI "
                "for d AUC is entirely above 0 ('-' for diagnostic rows):\n"
            )
            out.append(self._table(["comparison", "d AUC", "d AP", "CI>0"], rows))

            # Add per-history_bucket results for the final model (hybrid_val) and AE error alone
            if hybrid["per_seed"]:
                by_bucket_section = self._by_bucket_table(hybrid["per_seed"], "hybrid_val")
                if by_bucket_section:
                    out.append("\n" + by_bucket_section)

                # Add AE error-only per-bucket AUC
                ae_by_bucket_section = self._by_bucket_table(hybrid["per_seed"], "ae_error_only")
                if ae_by_bucket_section:
                    out.append("\n" + ae_by_bucket_section)

            out.append("")
        return "\n".join(out)

    def _baseline_by_bucket_table(self, ablation: dict) -> str:
        """Generate a side-by-side per-bucket table for all baseline variants."""
        from lstm_autoencoder.evaluation.paysim_synthetic_financial.baseline import HISTORY_STRATA_LABELS

        # Collect all variant names
        variant_names = list(ablation.keys())

        # Build table with variants as columns
        header = ["bucket"]
        for variant in variant_names:
            header.extend([f"{variant}_n", f"{variant}_n_fraud", f"{variant}_AUC", f"{variant}_AP"])

        rows = []
        for bucket_label in HISTORY_STRATA_LABELS:
            row = [bucket_label]
            for variant in variant_names:
                by_bucket = ablation[variant].get("by_bucket", {}).get(bucket_label, {})
                n = by_bucket.get("n", 0)
                n_fraud = by_bucket.get("n_fraud", 0)
                auc = by_bucket.get("auc", float("nan"))
                ap = by_bucket.get("ap", float("nan"))
                row.extend([
                    str(n),
                    str(n_fraud),
                    self._format(auc) if not str(auc) == "nan" else "-",
                    self._format(ap) if not str(ap) == "nan" else "-",
                ])
            rows.append(row)

        if not rows:
            return ""

        out = ["### Baseline per history bucket (side-by-side)\n"]
        out.append(self._table(header, rows))
        return "\n".join(out)

    def _by_bucket_table(self, per_seed: list[dict], variant_name: str) -> str:
        """Generate a table showing per-history_bucket metrics for a variant across seeds."""
        from lstm_autoencoder.evaluation.paysim_synthetic_financial.baseline import HISTORY_STRATA_LABELS

        # Aggregate across seeds for each bucket
        bucket_stats: dict[str, dict[str, list[float]]] = {}
        for seed_result in per_seed:
            by_bucket = seed_result.get("by_bucket", {}).get(variant_name, {})
            for bucket_label, metrics in by_bucket.items():
                if bucket_label not in bucket_stats:
                    bucket_stats[bucket_label] = {"auc": [], "ap": [], "n": [], "n_fraud": []}
                bucket_stats[bucket_label]["auc"].append(metrics.get("auc", float("nan")))
                bucket_stats[bucket_label]["ap"].append(metrics.get("ap", float("nan")))
                bucket_stats[bucket_label]["n"].append(metrics.get("n", 0))
                bucket_stats[bucket_label]["n_fraud"].append(metrics.get("n_fraud", 0))

        # Build table rows
        rows = []
        for bucket_label in HISTORY_STRATA_LABELS:
            if bucket_label not in bucket_stats:
                continue
            stats = bucket_stats[bucket_label]
            auc_values = [v for v in stats["auc"] if not str(v) == "nan"]
            ap_values = [v for v in stats["ap"] if not str(v) == "nan"]

            if auc_values:
                auc_mean = float(np.mean(auc_values))
                auc_std = float(np.std(auc_values, ddof=1 if len(auc_values) > 1 else 0))
            else:
                auc_mean = float("nan")
                auc_std = float("nan")

            if ap_values:
                ap_mean = float(np.mean(ap_values))
                ap_std = float(np.std(ap_values, ddof=1 if len(ap_values) > 1 else 0))
            else:
                ap_mean = float("nan")
                ap_std = float("nan")

            n = int(stats["n"][0]) if stats["n"] else 0
            n_fraud = int(stats["n_fraud"][0]) if stats["n_fraud"] else 0

            rows.append([
                bucket_label,
                str(n),
                str(n_fraud),
                self._format(auc_mean, auc_std) if not str(auc_mean) == "nan" else "-",
                self._format(ap_mean, ap_std) if not str(ap_mean) == "nan" else "-",
            ])

        if not rows:
            return ""

        header = f"#### {variant_name} per history bucket (mean ± std across seeds)\n"
        table = self._table(["bucket", "n", "n_fraud", "AUC", "AP"], rows)
        return header + table

    @staticmethod
    def _architecture_from_command(command: str) -> str:
        """Infer the architecture from the typed command (unverified)."""
        if "--bottleneck" in command:
            return "bottleneck"
        if "--attention-pooling" in command:
            return "attn_pool"
        if "--plain" in command:
            return "plain"
        return "attn"

    @staticmethod
    def _architecture_rank(architecture: str) -> int:
        """Sort key placing known architectures first, in the canonical order."""
        return ARCHITECTURE_ORDER.index(architecture) if architecture in ARCHITECTURE_ORDER else len(ARCHITECTURE_ORDER)

    @staticmethod
    def _ci_count(delta: dict) -> str:
        """'k/n' seeds whose bootstrap CI is above zero, or '-' for point-estimate-only rows."""
        if "seeds_auc_ci_above_0" not in delta:
            return "-"
        return f"{int(delta['seeds_auc_ci_above_0'])}/{int(delta['n_seeds'])}"

    @staticmethod
    def _format(mean: float, std: float | None = None, digits: int = 4) -> str:
        """Format `mean` or `mean ± std`."""
        return f"{mean:.{digits}f}" if std is None else f"{mean:.{digits}f} ± {std:.{digits}f}"

    @staticmethod
    def _table(header: list[str], rows: list[list[str]]) -> str:
        """Render a markdown table."""
        lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
        lines += ["| " + " | ".join(row) + " |" for row in rows]
        return "\n".join(lines)
